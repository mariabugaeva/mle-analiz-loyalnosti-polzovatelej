# main.py
import os
from src.processing import DataProcessor

def generate_report():
    """
    Главная функция запуска проекта.
    Управляет всем приложением: от загрузки данных до вывода отчета.
    """
    
    # 1. Определяем путь к файлу с курсами валют.
    # Используем os.path для кроссплатформенности (Windows / Mac / Linux)
    csv_path = os.path.join('data', 'final_tickets_tenge_df.csv')
    
    # 2. Инициализация класса (загрузка конфигураций)
    processor = DataProcessor(csv_path=csv_path)
    
    # 3. Запуск пайплайна предобработки (SQL, курсы, типы, очистка)
    processor.run_pipeline()
    
    # 4. Создание профилей пользователей
    processor.build_user_profile(filter_anomalies=True)
    
    # 5. Анализ Retention по сегментам (мероприятия, устройства, регионы)
    processor.analyze_segment_retention('event_type_main_first')
    processor.analyze_segment_retention('device_type_canonical_first')
    processor.analyze_segment_retention('region_name_first')
    
    # 6. Проверка продуктовых гипотез
    processor.check_hypotheses()
    
    # 7. Корреляционный анализ (plot=False, чтобы графики не блокировали терминал)
    processor.calculate_phik_correlation(target='order_id_count', plot=False)
    processor.calculate_phik_correlation(target='order_segment', plot=False)
    
    # 8. Вывод краткого итогового отчета в терминал
    print_final_report(processor)

